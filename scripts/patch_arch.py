def iter_paragraphs(doc):
    """依次产出正文段落与两张表单表格内的段落。"""
    for p in doc.paragraphs:
        yield p
    for table in doc.tables:
        for row in table.rows:
            keep, seen = [], set()
            for cell in row.cells:
                keep.append(cell)
                if id(cell._tc) in seen:
                    continue
                seen.add(id(cell._tc))
                for p in cell.paragraphs:
                    yield p


def set_paragraph_text(paragraph, text):
    """整段替换为 text，保留首个 run 的字符格式，清空其余 run。"""
    runs = list(paragraph.runs)
    if not runs:
        paragraph.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def delete_paragraph(paragraph):
    """删除段落，并顺带删掉紧邻的前一个空白段。"""
    el = paragraph._p
    parent = el.getparent()
    prev = el.getprevious()
    parent.remove(el)
    if prev is not None and prev.tag.endswith("}p") and "".join(prev.itertext()).strip() == "":
        parent.remove(prev)


def main():
    """按锚点执行整段改写或删除，幂等。"""
    dry = "--dry-run" in sys.argv
    doc = Document(str(DOCX))
    applied, skipped, missed = [], [], []
    for anchor, new in REWRITES:
        target = None
        for p in iter_paragraphs(doc):
            if anchor in p.text:
                target = p
                break
        if target is None:
            missed.append(anchor[:20])
            continue
        if new == "":
            delete_paragraph(target)
            applied.append("删除 " + anchor[:20])
            continue
        if new.replace(" ", "") == target.text.replace(" ", ""):
            skipped.append(anchor[:20])
            continue
        set_paragraph_text(target, new)
        applied.append("改写 " + anchor[:20])
    for a in applied:
        print("  OK  ", a)
    for s in skipped:
        print("  SKIP 已是目标文本:", s)
    for m in missed:
        print("  MISS 未命中:", m)
    if dry or not applied:
        print("未写入")
        return
    doc.core_properties.modified = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)
    doc.save(str(DOCX))
    print("已就地保存（不生成备份）:", DOCX.name, "bytes=", len(DOCX.read_bytes()))


if __name__ == "__main__":
    main()
