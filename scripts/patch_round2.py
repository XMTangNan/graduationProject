def set_para_text(par, text):
    runs = [r for r in par.runs if r.text]
    if not runs:
        par.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def main():
    doc = Document(str(DOCX))
    st = {"A": 0, "S": 0, "M": 0}
    for ti, ri, ci, anchor, new, guard in BIG:
        cell = doc.tables[ti].rows[ri].cells[ci]
        if guard in cell.text:
            st["S"] += 1
            continue
        hit = next((p for p in cell.paragraphs if anchor in p.text), None)
        if hit is None:
            st["M"] += 1
            print("BIG-MISS", anchor[:22])
            continue
        set_para_text(hit, new)
        st["A"] += 1
    for ti, ri, ci, old, new, guard in SMALL:
        cell = doc.tables[ti].rows[ri].cells[ci]
        if guard in cell.text:
            st["S"] += 1
            continue
        done = False
        for p in cell.paragraphs:
            if old in p.text:
                set_para_text(p, p.text.replace(old, new))
                st["A"] += 1
                done = True
                break
        if not done:
            st["M"] += 1
            print("SMALL-MISS", old[:24])
    doc.save(str(DOCX))
    print("saved", DOCX.stat().st_size, "applied", st["A"], "skipped", st["S"], "miss", st["M"])


if __name__ == "__main__":
    main()

